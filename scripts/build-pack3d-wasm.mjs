import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const crate = join(root, "native/pack3d");
execSync("cargo build --release --target wasm32-unknown-unknown", {
  cwd: crate,
  stdio: "inherit",
});
const wasmPath = join(crate, "target/wasm32-unknown-unknown/release/pack3d.wasm");
const bytes = readFileSync(wasmPath);
mkdirSync(join(root, "public"), { recursive: true });
writeFileSync(join(root, "public/pack3d.wasm"), bytes);
const b64 = bytes.toString("base64");
const out = `/* generated by scripts/build-pack3d-wasm.mjs — do not edit */
export const PACK3D_WASM = Uint8Array.from(atob(${JSON.stringify(b64)}), (c) => c.charCodeAt(0));
export const PACK3D_WASM_BYTES = ${bytes.length};
`;
writeFileSync(join(root, "src/lib/minmove/pack3d.wasm.ts"), out);
console.log(`[pack3d] ${bytes.length} bytes -> src/lib/minmove/pack3d.wasm.ts`);
